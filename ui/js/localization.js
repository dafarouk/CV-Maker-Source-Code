// ===========================================================
// TRANSLATE DOM
// ===========================================================

function cvmTranslateNode(
    root = document.body
) {

    if (
        !root
        || cvmI18nBusy
    ) {
        return;
    }


    cvmI18nBusy =
        true;


    try {

        const walker =
            document.createTreeWalker(

                root,

                NodeFilter.SHOW_TEXT,

                {

                    acceptNode(
                        node
                    ) {

                        const parent =
                            node.parentElement;


                        if (!parent) {
                            return NodeFilter.FILTER_REJECT;
                        }


                        if (
                            [
                                "SCRIPT",
                                "STYLE",
                                "TEXTAREA",
                                "INPUT"
                            ].includes(
                                parent.tagName
                            )
                        ) {
                            return NodeFilter.FILTER_REJECT;
                        }


                        return (
                            node.nodeValue?.trim()
                                ? NodeFilter.FILTER_ACCEPT
                                : NodeFilter.FILTER_REJECT
                        );
                    }

                }
            );


        const nodes =
            [];


        while (
            walker.nextNode()
        ) {
            nodes.push(
                walker.currentNode
            );
        }


        for (
            const node
            of nodes
        ) {

            let value =
                cvmTranslateValue(
                    node.nodeValue,
                    cvmCurrentLanguage
                );


            const trimmed =
                value.trim();


            const dynamic =
                cvmTranslateDynamicEnglish(
                    trimmed
                );


            if (
                dynamic
                !== trimmed
            ) {

                value =
                    value.replace(
                        trimmed,
                        dynamic
                    );
            }


            node.nodeValue =
                value;
        }


        root.querySelectorAll?.(
            "input[placeholder], textarea[placeholder]"
        ).forEach(
            (
                element
            ) => {

                element.placeholder =
                    cvmTranslateValue(
                        element.placeholder,
                        cvmCurrentLanguage
                    );
            }
        );


        root.querySelectorAll?.(
            "[title]"
        ).forEach(
            (
                element
            ) => {

                element.title =
                    cvmTranslateValue(
                        element.title,
                        cvmCurrentLanguage
                    );
            }
        );

    }
    finally {

        cvmI18nBusy =
            false;
    }
}


// ===========================================================
// LANGUAGE SWITCH
// ===========================================================

function cvmInstallLanguageSwitch() {

    if (
        document.querySelector(
            "#cvmLanguageToggle"
        )
    ) {
        return;
    }


    const actions =
        document.querySelector(
            ".topbar-actions"
        );


    if (!actions) {
        return;
    }


    const wrapper =
        document.createElement(
            "div"
        );


    wrapper.id =
        "cvmLanguageToggle";


    wrapper.className =
        "cvm-language-switch";


    wrapper.setAttribute(
        "aria-label",
        "Language"
    );


    wrapper.innerHTML = `
        <button
            type="button"
            data-cvm-language="en"
        >
            EN
        </button>

        <button
            type="button"
            data-cvm-language="fr"
        >
            FR
        </button>
    `;


    const connection =
        document.querySelector(
            "#connectionBadge"
        );


    if (connection) {

        actions.insertBefore(
            wrapper,
            connection
        );

    }
    else {

        actions.appendChild(
            wrapper
        );
    }


    wrapper.addEventListener(
        "click",
        (
            event
        ) => {

            const button =
                event.target.closest(
                    "[data-cvm-language]"
                );


            if (!button) {
                return;
            }


            cvmSetLanguage(
                button.dataset.cvmLanguage,
                true
            );
        }
    );
}


function cvmRefreshLanguageSwitch() {

    document.querySelectorAll(
        "[data-cvm-language]"
    ).forEach(
        (
            button
        ) => {

            button.classList.toggle(

                "active",

                button.dataset.cvmLanguage
                === cvmCurrentLanguage
            );
        }
    );
}


