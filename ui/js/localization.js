// SET LANGUAGE
// ===========================================================

function cvmSetLanguage(
    language,
    saveToProject = true
) {

    cvmCurrentLanguage =
        language === "fr"
            ? "fr"
            : "en";


    localStorage.setItem(
        "cvm-language",
        cvmCurrentLanguage
    );


    document.documentElement.lang =
        cvmCurrentLanguage;


    if (
        typeof state !== "undefined"
        && state.project
    ) {

        state.project.design ||= {};


        state.project.design.language =
            cvmCurrentLanguage;


        if (
            saveToProject
            && typeof projectChanged
            === "function"
        ) {

            projectChanged();
        }
    }


    cvmRefreshLanguageSwitch();


    cvmTranslateNode(
        document.body
    );


    if (
        typeof cvmRenderSectionOrderList
        === "function"
    ) {

        cvmRenderSectionOrderList();


        cvmTranslateNode(
            document.querySelector(
                "#sectionOrderList"
            )
        );
    }


    if (
        typeof renderDynamicSections
        === "function"
        && state?.project
    ) {

        renderDynamicSections();


        cvmTranslateNode(
            document.querySelector(
                "#editorRoot"
            )
        );
    }


    if (
        typeof renderPreview
        === "function"
        && state?.project
    ) {

        renderPreview();


        cvmTranslateNode(
            document.querySelector(
                "#cvPreview"
            )
        );
    }
}


