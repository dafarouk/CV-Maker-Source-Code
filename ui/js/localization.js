// ===========================================================
// BASE TRANSLATION
// ===========================================================

function cvmTranslateValue(
    value,
    language
) {

    const raw =
        String(
            value ?? ""
        );


    const trimmed =
        raw.trim();


    if (!trimmed) {
        return raw;
    }


    const englishKey =
        CVM_I18N.en[
            trimmed
        ] !== undefined
            ? trimmed
            : (
                CVM_FR_TO_EN[
                    trimmed
                ]
                || trimmed
            );


    const translated =
        CVM_I18N[
            language
        ]?.[
            englishKey
        ];


    if (
        translated
        === undefined
    ) {
        return raw;
    }


    const leading =
        raw.match(
            /^\s*/
        )?.[0]
        || "";


    const trailing =
        raw.match(
            /\s*$/
        )?.[0]
        || "";


    return (
        leading
        + translated
        + trailing
    );
}


