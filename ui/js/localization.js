// ===========================================================
// OBSERVE DYNAMIC UI
// ===========================================================

const cvmI18nObserver =
    new MutationObserver(
        (
            mutations
        ) => {

            if (
                cvmI18nBusy
            ) {
                return;
            }


            for (
                const mutation
                of mutations
            ) {

                for (
                    const node
                    of mutation.addedNodes
                ) {

                    if (
                        node.nodeType
                        === Node.ELEMENT_NODE
                    ) {

                        cvmTranslateNode(
                            node
                        );

                    }
                    else if (
                        node.nodeType
                        === Node.TEXT_NODE
                        && node.parentElement
                    ) {

                        cvmTranslateNode(
                            node.parentElement
                        );
                    }
                }
            }
        }
    );


// ===========================================================
// START
// ===========================================================

function cvmStartLocalization() {

    cvmInstallLanguageSwitch();


    cvmRefreshLanguageSwitch();


    cvmSetLanguage(

        state?.project?.design?.language
        || localStorage.getItem(
            "cvm-language"
        )
        || "en",

        false
    );


    cvmI18nObserver.observe(

        document.body,

        {
            childList: true,
            subtree: true
        }
    );
}


document.addEventListener(
    "DOMContentLoaded",
    cvmStartLocalization
);